const GENERATED_BY: &str = "eatme-assets gadugi adapter generator";
const GENERATED_FILE_HEADER: &str = "# DO NOT EDIT: generated by eatme-assets from canonical eatme scenario assets.\n# Non-coders: edit the matching source YAML under assets/scenarios/eatme/, then ask a maintainer to run `eatme assets generate-gadugi`.\n";

pub fn generate_gadugi_adapters(root: &Path, check: bool) -> Result<GadugiAdapterGenerationReport> {
    let eatme_root = root.join("assets/scenarios/eatme");
    let gadugi_root = root.join("assets/scenarios/gadugi");
    let source_paths = scenario_asset_paths(&eatme_root)?;
    let expected_scenario_asset_count = scenario_asset_paths(&root.join("assets/scenarios"))?.len();
    let mut report = GadugiAdapterGenerationReport {
        schema_version: "eatme.assets/gadugi-adapter-generation/v1".into(),
        root: root.display().to_string(),
        generated_count: 0,
        checked_count: 0,
        changed: Vec::new(),
        passed: true,
        errors: Vec::new(),
    };

    if !check {
        fs::create_dir_all(&gadugi_root)
            .with_context(|| format!("creating {}", gadugi_root.display()))?;
    }

    for source_path in source_paths {
        let yaml = generate_gadugi_adapter_yaml_with_count(
            root,
            &source_path,
            expected_scenario_asset_count,
        )?;
        let scenario = read_eatme_scenario(&source_path)?;
        let target_path = gadugi_root.join(format!("{}.yaml", scenario.id));
        report.generated_count += 1;
        if check {
            report.checked_count += 1;
            match fs::read_to_string(&target_path) {
                Ok(existing) if existing == yaml => {}
                Ok(_) => {
                    report.passed = false;
                    report.changed.push(target_path.display().to_string());
                    report.errors.push(format!(
                        "{} is stale; regenerate with `eatme assets generate-gadugi`",
                        target_path.display()
                    ));
                }
                Err(error) => {
                    report.passed = false;
                    report.changed.push(target_path.display().to_string());
                    report.errors.push(format!(
                        "{} is missing or unreadable: {error}",
                        target_path.display()
                    ));
                }
            }
        } else {
            let changed = fs::read_to_string(&target_path)
                .map(|existing| existing != yaml)
                .unwrap_or(true);
            if changed {
                fs::write(&target_path, yaml)
                    .with_context(|| format!("writing {}", target_path.display()))?;
                report.changed.push(target_path.display().to_string());
            }
        }
    }

    Ok(report)
}

pub fn generate_gadugi_adapter_yaml(root: &Path, source_path: &Path) -> Result<String> {
    let expected_scenario_asset_count = scenario_asset_paths(&root.join("assets/scenarios"))?.len();
    generate_gadugi_adapter_yaml_with_count(root, source_path, expected_scenario_asset_count)
}

fn generate_gadugi_adapter_yaml_with_count(
    root: &Path,
    source_path: &Path,
    expected_scenario_asset_count: usize,
) -> Result<String> {
    let scenario = read_eatme_scenario(source_path)?;
    let source_asset = source_path
        .strip_prefix(root)
        .with_context(|| {
            format!(
                "scenario asset {} is not under root {}",
                source_path.display(),
                root.display()
            )
        })?
        .to_string_lossy()
        .replace('\\', "/");
    if scenario.id.is_empty() {
        bail!("{} must define id", source_path.display());
    }

    let timeout_ms = scenario_timeout_ms(&scenario);
    let launch_timeout = scenario
        .timeouts
        .get("launch_seconds")
        .copied()
        .unwrap_or(900);
    let run_id = format!("gadugi-{}", scenario.id);

    if scenario.kind == "instructor_agentic_flow" {
        return generate_instructor_agentic_adapter(&scenario, source_asset, timeout_ms);
    }

    let steps = scenario
        .steps
        .iter()
        .map(|step| {
            generated_step(
                &scenario,
                step,
                &run_id,
                launch_timeout,
                expected_scenario_asset_count,
            )
        })
        .collect::<Vec<_>>();
    let assertions = scenario
        .steps
        .iter()
        .map(|step| {
            generated_assertion(
                &scenario,
                step,
                "eatme-cli-agent",
                expected_scenario_asset_count,
            )
        })
        .collect::<Vec<_>>();

    let adapter = GeneratedGadugiAdapter {
        name: format!("Eatme {}", scenario.title),
        description: format!(
            "Gadugi-compatible CLI scenario generated from {source_asset}. Alice desktop launch behavior remains owned by eatme; gadugi invokes eatme commands and checks manifest-level evidence only."
        ),
        version: "1.0.0".into(),
        config: GeneratedConfig {
            timeout: timeout_ms,
            retries: 0,
            parallel: false,
        },
        environment: GeneratedEnvironment {
            requires: required_environment(&scenario),
            optional: vec!["RUN_ID".into(), "EATME_REPO".into()],
        },
        agents: vec![GeneratedAgent {
            name: "eatme-cli-agent".into(),
            agent_type: "system".into(),
            config: GeneratedAgentConfig {
                shell: Some("bash".into()),
                cwd: Some(".".into()),
                timeout: timeout_ms,
                capture_output: Some(true),
                persona_asset: None,
                scenario_asset: None,
            },
        }],
        steps,
        assertions,
        metadata: GeneratedMetadata {
            source_eatme_asset: source_asset,
            generated_by: GENERATED_BY.into(),
            tags: vec![
                "alice".into(),
                "eatme".into(),
                "gadugi".into(),
                "outside-in".into(),
                scenario.id.clone(),
            ],
            priority: "critical".into(),
            author: "eatme".into(),
            test_type: match scenario.kind.as_str() {
                "alice_real_ui_action_contract" => "ui-action-contract",
                _ => "launch-smoke",
            }
            .into(),
        },
    };

    render_yaml(adapter)
}

fn read_eatme_scenario(path: &Path) -> Result<EatmeScenarioAsset> {
    let content = fs::read_to_string(path)
        .with_context(|| format!("reading eatme scenario asset {}", path.display()))?;
    serde_yaml::from_str(&content)
        .with_context(|| format!("parsing eatme scenario YAML {}", path.display()))
}

fn render_yaml(adapter: GeneratedGadugiAdapter) -> Result<String> {
    let mut yaml = GENERATED_FILE_HEADER.to_string();
    yaml.push_str(&serde_yaml::to_string(&adapter).context("serializing gadugi adapter YAML")?);
    if !yaml.ends_with('\n') {
        yaml.push('\n');
    }
    Ok(yaml)
}

fn generated_step(
    scenario: &EatmeScenarioAsset,
    step: &EatmeScenarioStep,
    run_id: &str,
    launch_timeout: u64,
    expected_scenario_asset_count: usize,
) -> GeneratedStep {
    let command = repository_command(step.command.trim(), run_id);
    GeneratedStep {
        name: step_title(&step.id),
        agent: "eatme-cli-agent".into(),
        action: "execute_command".into(),
        params: BTreeMap::from([("command".into(), command)]),
        expect: GeneratedExpect {
            exit_code: Some(expected_exit_code(scenario, step)),
            stdout_contains: Some(expected_stdout(
                scenario,
                step,
                expected_scenario_asset_count,
            )),
            output_contains: None,
        },
        timeout: step_timeout_ms(&step.id, launch_timeout),
    }
}

fn command_success_assertion(step_id: &str, agent: &str) -> GeneratedAssertion {
    GeneratedAssertion {
        name: format!("{step_id} succeeds"),
        assertion_type: "command_success".into(),
        agent: agent.into(),
        params: BTreeMap::from([("step".into(), step_title(step_id))]),
    }
}

fn generated_assertion(
    scenario: &EatmeScenarioAsset,
    step: &EatmeScenarioStep,
    agent: &str,
    expected_scenario_asset_count: usize,
) -> GeneratedAssertion {
    if expected_exit_code(scenario, step) == 0 {
        return command_success_assertion(&step.id, agent);
    }

    GeneratedAssertion {
        name: format!("{} expected failure is explicit", step.id),
        assertion_type: "output_contains_all".into(),
        agent: agent.into(),
        params: BTreeMap::from([
            ("step".into(), step_title(&step.id)),
            (
                "required_strings".into(),
                expected_stdout(scenario, step, expected_scenario_asset_count).join("\n"),
            ),
        ]),
    }
}

fn scenario_timeout_ms(scenario: &EatmeScenarioAsset) -> u64 {
    scenario
        .timeouts
        .get("scenario_seconds")
        .or_else(|| scenario.timeouts.get("agentic_seconds"))
        .copied()
        .unwrap_or(1800)
        * 1000
}

fn repository_command(command: &str, run_id: &str) -> String {
    format!("cd \"${{EATME_REPO:-.}}\"\nexport RUN_ID=\"${{RUN_ID:-{run_id}}}\"\n{command}")
}

fn step_title(id: &str) -> String {
    id.split('-')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => format!("{}{}", first.to_uppercase(), chars.as_str()),
                None => String::new(),
            }
        })
        .collect::<Vec<_>>()
        .join(" ")
}

fn step_timeout_ms(step_id: &str, launch_timeout: u64) -> u64 {
    if step_id.contains("launch") {
        launch_timeout * 1000
    } else {
        60_000
    }
}

fn expected_exit_code(scenario: &EatmeScenarioAsset, step: &EatmeScenarioStep) -> u64 {
    if is_launch_step(&step.id, &step.command) && scenario.kind == "alice_real_ui_action_contract" {
        1
    } else {
        0
    }
}

fn expected_stdout(
    scenario: &EatmeScenarioAsset,
    step: &EatmeScenarioStep,
    expected_scenario_asset_count: usize,
) -> Vec<String> {
    let step_id = step.id.as_str();
    let command = step.command.as_str();
    if command.contains("assets validate") {
        let mut expected = vec!["\"passed\": true".into()];
        if command.contains("--path") {
            expected.push(format!("\"id\": \"{}\"", scenario.id));
        } else {
            expected.push(format!(
                "\"scenario_asset_count\": {expected_scenario_asset_count}"
            ));
        }
        return expected;
    }
    if step_id.contains("dependencies") {
        return vec!["\"all_required_available\": true".into()];
    }
    if step_id.contains("discover") {
        return vec!["\"alice_ide_jar_exists\": true".into()];
    }
    if is_launch_step(step_id, command) {
        return launch_expected_stdout(scenario, step);
    }
    Vec::new()
}

fn is_launch_step(step_id: &str, command: &str) -> bool {
    step_id.contains("launch")
        || step_id.contains("smoke")
        || command.contains("alice launch-smoke")
}

fn launch_expected_stdout(scenario: &EatmeScenarioAsset, step: &EatmeScenarioStep) -> Vec<String> {
    let evidence = step.evidence.join("\n").to_lowercase();
    let mut expected = vec![format!("\"scenario_id\": \"{}\"", scenario.id)];
    if scenario.kind == "alice_real_ui_action_contract" {
        expected.push("\"failure_category\": \"ui_action_automation_unimplemented\"".into());
    } else {
        expected.push("\"failure_category\": null".into());
    }
    expected.push("\"real_alice_execution_evidence\": {".into());

    if evidence.contains("screenshot or window") {
        expected.push("\"startup_window_or_screenshot\": {".into());
    } else if evidence.contains("screenshot") {
        expected.push("\"startup_screenshot\": {".into());
    }

    for assertion in [
        "specific_alice_window_detected",
        "place_object_ui_action",
        "edit_procedure_ui_action",
        "run_world_ui_action",
        "save_project_ui_action",
        "ui_action_artifact_captured",
    ] {
        if evidence.contains(assertion) {
            expected.push(format!("\"{assertion}\": {{"));
        }
    }
    if evidence.contains("ui-action-contract.json") {
        expected.push("\"ui_action_contract\": {".into());
    }
    if evidence.contains("africa.a3p") {
        expected.push("africa.a3p".into());
    }
    if evidence.contains("assertions all pass") || evidence.contains("passed=true") {
        expected.push("\"passed\": true".into());
    }
    expected
}

fn required_environment(scenario: &EatmeScenarioAsset) -> Vec<String> {
    let mut required = vec!["ALICE_HOME".into()];
    if scenario
        .real_alice
        .as_ref()
        .map(|real_alice| real_alice.gated_by == "EATME_REAL_ALICE=1")
        .unwrap_or(false)
    {
        required.push("EATME_REAL_ALICE".into());
    }
    required
}

#[derive(Serialize)]
struct GeneratedGadugiAdapter {
    name: String,
    description: String,
    version: String,
    config: GeneratedConfig,
    environment: GeneratedEnvironment,
    agents: Vec<GeneratedAgent>,
    steps: Vec<GeneratedStep>,
    assertions: Vec<GeneratedAssertion>,
    metadata: GeneratedMetadata,
}

#[derive(Serialize)]
struct GeneratedConfig {
    timeout: u64,
    retries: u64,
    parallel: bool,
}

#[derive(Serialize)]
struct GeneratedEnvironment {
    requires: Vec<String>,
    optional: Vec<String>,
}

#[derive(Serialize)]
struct GeneratedAgent {
    name: String,
    #[serde(rename = "type")]
    agent_type: String,
    config: GeneratedAgentConfig,
}

#[derive(Serialize)]
struct GeneratedAgentConfig {
    #[serde(skip_serializing_if = "Option::is_none")]
    shell: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    cwd: Option<String>,
    timeout: u64,
    #[serde(skip_serializing_if = "Option::is_none")]
    capture_output: Option<bool>,
    #[serde(skip_serializing_if = "Option::is_none")]
    persona_asset: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    scenario_asset: Option<String>,
}

#[derive(Serialize)]
struct GeneratedStep {
    name: String,
    agent: String,
    action: String,
    params: BTreeMap<String, String>,
    expect: GeneratedExpect,
    timeout: u64,
}

#[derive(Serialize)]
struct GeneratedExpect {
    #[serde(skip_serializing_if = "Option::is_none")]
    exit_code: Option<u64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    stdout_contains: Option<Vec<String>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    output_contains: Option<Vec<String>>,
}

#[derive(Serialize)]
struct GeneratedAssertion {
    name: String,
    #[serde(rename = "type")]
    assertion_type: String,
    agent: String,
    params: BTreeMap<String, String>,
}

#[derive(Serialize)]
struct GeneratedMetadata {
    source_eatme_asset: String,
    generated_by: String,
    tags: Vec<String>,
    priority: String,
    author: String,
    test_type: String,
}

